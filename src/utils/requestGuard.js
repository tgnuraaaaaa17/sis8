/**
 * ============================================================================
 *  requestGuard.js — race condition қорғауы (race condition guard)
 * ============================================================================
 *
 *  Мәселе: fake API жауапты 500–3000 ms кездейсоқ кідірісімен қайтарады.
 *  Егер қолданушы екі item-ді тез жылдамдырып таңдаса, жауаптар ОРНДЫҢ
 *  қайтарылуы мүмкін: бірінші сұраныс кешірек қайтарылса, ескі деталь
 *  экранда көрініп, «жаңа» item-дің орнына көрсетіледі (бұл — race condition).
 *
 *  Шешім: әр сұранысқа монотондық сан (id) беріледі. Жауап келгенде
 *  тексеріледі: «мен — соңғы сұраныс па?» Егер жоқ, жауап тасталады.
 *
 *  Неге useRef ЕМЕС? Тапсырмада рұқсат етілген hook-тар тек useState және
 *  useEffect. Сондықтан «саншы» модуль деңгейіндегі қарапайым айнымалыда
 *  сақталады — ол React-ке тәуелді емес, тек сұраныс ретін нөмірлейді.
 *
 *  Екі бөлек канал бар (list / details), себебі тізімді қайта жүктеу
 *  бөліктердің сұранысын күшіне кіруге тиіс емес.
 * ============================================================================
 */

let listCounter = 0;
let detailCounter = 0;

/** Жаңа тізім сұранысын бастатады → оның нөмірін қайтарады. */
export function beginListRequest() {
  listCounter += 1;
  return listCounter;
}

/** Жауап әлі «ең соңғы» сұранысқа тиесі пе? */
export function isLatestListRequest(requestId) {
  return requestId === listCounter;
}

/** Жаңа деталь сұранысын бастатады → оның нөмірін қайтарады. */
export function beginDetailRequest() {
  detailCounter += 1;
  return detailCounter;
}

/** Жауап әлі «ең соңғы» деталь сұранысына тиесі пе? */
export function isLatestDetailRequest(requestId) {
  return requestId === detailCounter;
}
