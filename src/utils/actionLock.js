/**
 * ============================================================================
 *  actionLock.js — қарсы әрекеттерді (conflicting actions) блоктау
 * ============================================================================
 *
 *  Тапсырма: «capture the selected item's ID when starting completion,
 *  prevent conflicting actions».
 *
 *  Неге state бірлігі жеткіліксіз? React-те setState асинхронды: егер
 *  қолданушы батырманы екі рет өте қатты басса, екінші басу әлі
 *  «pending» жаңаланбаған күйден (state) орын алмауы мүмкін → екі сұраныс
 *  қатар жүреді.
 *
 *  Шешім: «жабылған» id-лердің нақты тізімі модуль деңгейіндегі Set-те
 *  сақталады (useRef қолданбаймыз). Lock — бұл де бір «орыннан тыс» күй,
 *  ол React-тің рендер цикліне қатыспайды.
 *
 *  UI-да «pending» күйін көрсету үшін App-те useState бар (pendingIds),
 *  бірақ «шыны» құлыптау осында.
 * ============================================================================
 */

const lockedIds = new Set();

/** Осы id үшін әрекет қазір жүріп жатыр ма? */
export function isActionLocked(id) {
  return lockedIds.has(id);
}

/** Әрекетті бастау → құлыптаймыз (бір уақытта бір әрекет). */
export function lockAction(id) {
  lockedIds.add(id);
}

/** Әрекет аяқталды (немесе қате шықты) → құлыпты аламыз. */
export function unlockAction(id) {
  lockedIds.delete(id);
}
